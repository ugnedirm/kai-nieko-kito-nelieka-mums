// Dependency-free build: (1) regenerate src/generated/prompt.js from the Python package's prompt
// (single source of truth), (2) assemble dist/chrome and dist/firefox. Zip with `web-ext build`
// or `zip -r` for store upload.
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const ext = join(here, "..");
const promptFile = join(ext, "..", "src", "threadvault", "agent", "prompts", "handover_v1.txt");

export function promptSource() {
  const text = readFileSync(promptFile, "utf8");
  return "// GENERATED by tools/build.mjs from src/threadvault/agent/prompts/handover_v1.txt. Do not edit.\n" +
    "(function (root) {\n  (root.TV = root.TV || {}).prompt = { version: \"1\", text: " + JSON.stringify(text) + " };\n})(globalThis);\n";
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  mkdirSync(join(ext, "src", "generated"), { recursive: true });
  writeFileSync(join(ext, "src", "generated", "prompt.js"), promptSource());
  for (const [target, manifest] of [["chrome", "manifest.json"], ["firefox", "manifest.firefox.json"]]) {
    const out = join(ext, "dist", target);
    rmSync(out, { recursive: true, force: true });
    mkdirSync(out, { recursive: true });
    cpSync(join(ext, "src"), join(out, "src"), { recursive: true });
    cpSync(join(ext, "pages"), join(out, "pages"), { recursive: true });
    cpSync(join(ext, manifest), join(out, "manifest.json"));
    console.log("built", out);
  }
}
